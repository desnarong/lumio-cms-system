export type MessageParams = Record<string, string | number>;

/** Replaces `{name}` placeholders; unknown placeholders stay untouched. */
export const interpolate = (message: string, params: MessageParams = {}): string =>
  message.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );

export type Translate = (key: MessageKey, params?: MessageParams) => string;

/**
 * Translator for one language. Missing translations answer in Thai, and an
 * unknown key answers with the key itself so a bug is visible instead of silent.
 */
export const createTranslator = (locale: UiLocale): Translate => {
  const catalogue = locale === 'en' ? EN_MESSAGES : TH_MESSAGES;
  return (key, params) => {
    const message = catalogue[key] ?? TH_MESSAGES[key] ?? key;
    return interpolate(message, params);
  };
};

const MessagesContext = createContext<Translate>(createTranslator('th'));
const LocaleContext = createContext<UiLocale>('th');

/** Language of the mounted provider; Thai before any provider mounts. */
let activeLocale: UiLocale = 'th';

export interface MessagesProviderProps {
  locale: UiLocale;
  children: ReactNode;
}

/**
 * Makes one language available to every component below it. The translator is
 * memoised per language so callbacks that list `t` as a dependency stay stable
 * (otherwise every render would re-run their effects).
 */
export const MessagesProvider = ({ locale, children }: MessagesProviderProps) => {
  // Kept in step during render (not in an effect) so text built outside React,
  // such as an API client's network fallback, is already right on the first paint.
  activeLocale = locale;
  const value = useMemo(() => createTranslator(locale), [locale]);
  return (
    <LocaleContext.Provider value={locale}>
      <MessagesContext.Provider value={value}>{children}</MessagesContext.Provider>
    </LocaleContext.Provider>
  );
};

/** The language of the surrounding provider, or Thai when there is none. */
export const useUiLocale = (): UiLocale => useContext(LocaleContext);

/** The translator of the surrounding provider, or Thai when there is none. */
export const useT = (): Translate => useContext(MessagesContext);

/**
 * Translates outside React, so text created by an API client (a network
 * failure, for example) still reads in the user's language.
 */
export const translateNow = (key: MessageKey, params?: MessageParams): string =>
  createTranslator(activeLocale)(key, params);

/** The language of the mounted provider, for code outside React (demo clients). */
export const uiLocaleNow = (): UiLocale => activeLocale;

/** Languages a picker offers, in the order the product lists them. */
export const uiLocaleOptions = (): { value: UiLocale; label: string }[] =>
  UI_LOCALES.map((locale) => ({ value: locale, label: UI_LOCALE_LABELS[locale] }));

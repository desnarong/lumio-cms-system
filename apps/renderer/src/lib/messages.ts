export type StorefrontParams = Record<string, string | number>;
export type StorefrontT = (key: StorefrontKey, params?: StorefrontParams) => string;

const interpolate = (message: string, params: StorefrontParams = {}): string =>
  message.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );

/** Translator for one request's language. */
export const storefrontT = (locale: string | null | undefined): StorefrontT => {
  const catalogue = storefrontLocale(locale) === 'en' ? EN : TH;
  return (key, params) => interpolate(catalogue[key], params);
};

/** A baht amount in the reader's language: "1,200 บาท" or "฿1,200". */
export const money = (t: StorefrontT, amount: number): string =>
  t('common.money', { amount: formatBaht(amount) });

/** Shipping line: "ฟรี"/"Free" for zero, otherwise the amount. */
export const shippingFee = (t: StorefrontT, amount: number): string =>
  amount === 0 ? t('common.free') : money(t, amount);

/** `Intl` locale tag for numbers and dates in the storefront. */
export const storefrontIntlLocale = (locale: string | null | undefined): string =>
  storefrontLocale(locale) === 'en' ? 'en-GB' : 'th-TH';
